def setup_browser():
    chrome_options = Options()
    # 봇 차단 방지를 위해 헤드리스 모드보다는 실제 브라우저를 띄우는 것이 좋습니다.
    # 만약 화면이 뜨는 게 싫다면 아래 주석을 해제하세요.
    # chrome_options.add_argument("--headless")
    chrome_options.add_argument("--no-sandbox")
    chrome_options.add_argument("user-agent=Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36")
    return webdriver.Chrome(service=Service(ChromeDriverManager().install()), options=chrome_options)

def check_nickname(driver, word):
    url = f"https://fconline.nexon.com/datacenter/searchmanager?strNickname={word}"
    driver.get(url)
    
    try:
        # 10초 동안 아래 두 조건 중 하나가 나타날 때까지 대기
        # .no_data: 검색 결과 없음
        # .list_st1: 검색 결과 있음 (리스트)
        WebDriverWait(driver, 10).until(
            lambda d: d.find_elements(By.CLASS_NAME, "no_data") or d.find_elements(By.CLASS_NAME, "list_st1")
        )
        
        # 나타난 요소 확인
        if driver.find_elements(By.CLASS_NAME, "no_data"):
            return "없음"
        else:
            return "있음"
            
    except:
        return "확인불가"

def main():
    driver = setup_browser()
    results = []
    
    print(f"⚠️ 총 {len(WORD_LIST)}개 단어 검사를 시작합니다.")
    
    for idx, word in enumerate(WORD_LIST, 1):
        status = check_nickname(driver, word)
        print(f"[{idx:04d}/{len(WORD_LIST)}] '{word}' -> {status}")
        results.append({"단어": word, "상태": status})
        
        # 넥슨 서버 부하 방지 및 차단 회피용 랜덤 대기 (1초 ~ 2.5초)
        time.sleep(random.uniform(1.0, 2.5)) 

    driver.quit()
    
    # 엑셀 저장
    df = pd.DataFrame(results)
    df.to_excel("fc_online_result_final.xlsx", index=False)
    print("\n🎉 작업 완료: 'fc_online_result_final.xlsx' 파일이 생성되었습니다.")

